-- 0013：文件监听默认值翻转（2026-10-24 用户决策修订，性能优先）
-- 背景：0001 种子行把 watch_enabled 恒置 '1'，启动时对全部已登记项目做 chokidar
-- 初始递归遍历（ignored 为逐路径 JS 函数），项目多/大时首启 CPU/IO 风暴拖慢开屏。
-- 决策：默认改为关闭（手动在设置里开启）。本迁移一次性把存量 '1' 翻成 '0'——
-- 此后用户在设置里手动开启会写回 '1'，后续升级不会再被翻转（本迁移只跑一次）。
-- 代价：极少数此前显式开启监听的现有安装升级后被静默关闭，需在发版说明写明。
UPDATE settings SET value = '0', updated_at = datetime('now')
WHERE key = 'watch_enabled' AND value = '1';
